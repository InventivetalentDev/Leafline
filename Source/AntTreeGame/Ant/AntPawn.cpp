void AAntPawn::EndPlay(const EEndPlayReason::Type EndPlayReason)
{
	// Loops belong to the world's audio subsystem and would outlive the pawn (a new day destroys ants mid-cut).
	LeafSound::Stop(CutLoop);
	LeafSound::Stop(GripLoop);
	Super::EndPlay(EndPlayReason);
}

void AAntPawn::UnPossessed()
{
	Super::UnPossessed();
	bCutHeld = false;
	bFollowHeld = false;
	bGripHeld = false;
	LeafSound::Stop(GripLoop);
	if (Movement)
	{
		Movement->SetMoveInput(FVector2D::ZeroVector, FVector::ForwardVector, FVector::UpVector);
		Movement->SetSprintInput(false);
		if (Movement->GetState() == EAntState::Riding) Movement->StopFollow();
		if (Movement->GetState() == EAntState::Gripping) Movement->SetState(EAntState::Walking);
	}
}

void AAntPawn::Tick(float DeltaSeconds)
{
	Super::Tick(DeltaSeconds);
	if (bSimDriven) return;
	StepLogic(DeltaSeconds, true);
}

void AAntPawn::MakeRecruit(ALineSystem* InOwner)
{
	bRecruit = true;
	LineOwner = InOwner;
	SetSimDriven(true);
}

void AAntPawn::SetSimDriven(bool bDriven)
{
	bSimDriven = bDriven;
	if (Movement) Movement->SetExternalStep(bDriven);
}

void AAntPawn::SimStep(float Dt, bool bVisuals)
{
	if (!Movement) return;
	if (VanishTime < 0.f) Movement->Step(Dt, bVisuals);
	StepLogic(Dt, bVisuals);
}

void AAntPawn::PushVisuals()
{
	if (!Movement || VanishTime >= 0.f) return;
	Movement->ApplyTransformNow();
	// A recruit's piece never shrinks below a few pixels on screen, so a line of them reads from a branch away (and in
	// the harvest view from the nest). Looks only: the wind still sees the real size.
	if (bRecruit && IsCarrying() && FragmentMesh && SwingTime < 0.f && FlutterTime < 0.f && FragmentMesh->GetAttachParent() == CarrySocket)
	{
		float Scale = 1.f;
		const APlayerController* PC = GetWorld() ? GetWorld()->GetFirstPlayerController() : nullptr;
		if (PC && PC->PlayerCameraManager && GEngine && GEngine->GameViewport)
		{
			FVector2D Viewport(1920.0, 1080.0);
			GEngine->GameViewport->GetViewportSize(Viewport);
			const float Dist = (float)FVector::Dist(PC->PlayerCameraManager->GetCameraLocation(), GetActorLocation());
			const float HalfTan = FMath::Tan(FMath::DegreesToRadians(PC->PlayerCameraManager->GetFOVAngle() * 0.5f));
			const float Pixels = DiameterForSize(CarriedSize) / FMath::Max(2.f * Dist * HalfTan, 1.f) * (float)Viewport.X;
			Scale = FMath::Clamp(9.f / FMath::Max(Pixels, 0.1f), 1.f, 6.f);
		}
		FragmentMesh->SetRelativeScale3D(FVector(Scale));
	}
	if (BodyMID)
	{
		BodyMID->SetScalarParameterValue(TEXT("GaitPhase"), GaitPhase);
		BodyMID->SetScalarParameterValue(TEXT("GaitAmount"), GaitAmount);
	}
	UpdateSounds();
}

void AAntPawn::StartAutoCut(int32 Leaf, float Size)
{
	ATreeActor* Tree = GetTree();
	if (!Tree || IsCarrying() || IsCutting()) return;
	CuttingLeaf = Leaf;
	CutSize = 0.f;
	CutCap = FMath::Max(Size, Cut.MinSize);
	bAutoCut = true;
	if (Movement->GetState() == EAntState::Riding || Movement->GetState() == EAntState::Returning) Movement->StopFollow();
	Movement->SetState(EAntState::Cutting);
}

void AAntPawn::StepLogic(float DeltaSeconds, bool bVisuals)
{
	if (!Movement) return;
	UpdateFlutter(DeltaSeconds);
	if (VanishTime >= 0.f)
	{
		UpdateVanish(DeltaSeconds);
		return;
	}

	// A leaf within reach of the mouth, for the prompt and for cutting.
	LeafInReach = INDEX_NONE;
	const EAntState State = Movement->GetState();
	if (IsPlayerControlled() && !IsCarrying() && (State == EAntState::Walking || State == EAntState::Cutting))
	{
		if (ATreeActor* Tree = GetTree())
		{
			LeafInReach = Tree->FindLeafNear(GetActorTransform().TransformPosition(MandibleOffset), Cut.Reach);
		}
	}

	UpdateCutting(DeltaSeconds);
	UpdateCutVisuals(DeltaSeconds);
	UpdateRiding(DeltaSeconds);
	UpdateGrip();
	UpdateRecording();
	UpdateWind(DeltaSeconds);
	if (bVisuals) UpdateSounds();

	// Gait: the legs cycle with distance walked (GaitStrideCm per cycle, at most GaitMaxHz) and settle when the ant stops.
	if (BodyMID)
	{
		const EAntState GaitState = Movement->GetState();
		const bool bLegsStill = GaitState == EAntState::Falling || GaitState == EAntState::Gripping || GaitState == EAntState::Cutting;
		const float Speed = bLegsStill ? 0.f : (float)Movement->GetVelocity().Size();
		const float CycleHz = FMath::Min(Speed / FMath::Max(Movement->Tuning.GaitStrideCm, 1.f), FMath::Max(Movement->Tuning.GaitMaxHz, 0.1f));
		GaitPhase = FMath::Fmod(GaitPhase + CycleHz * DeltaSeconds * 2.f * PI, 2.f * PI);
		GaitAmount = FMath::FInterpTo(GaitAmount, FMath::Clamp(Speed / 120.f, 0.f, 1.f), DeltaSeconds, 8.f);
		if (bVisuals)
		{
			BodyMID->SetScalarParameterValue(TEXT("GaitPhase"), GaitPhase);
			BodyMID->SetScalarParameterValue(TEXT("GaitAmount"), GaitAmount);
		}
	}

	// Recruits answer to the line system, which watches their progress itself.
	if (bRecruit) return;
	ADayDirector* Director = GetDirector();
	if (!Director) return;
	if (Movement->ConsumeFollowFinished() && Movement->GetState() == EAntState::Returning)
	{
		Director->OnAntReachedNest(this);
		return;
	}
	if (Movement->GetState() == EAntState::WalkingHome)
	{
		if (ANestActor* Nest = Director->GetNest())
		{
			const FVector TrunkBase = GetTree() ? GetTree()->GetSkeleton().TrunkBase : FVector::ZeroVector;
			Movement->SetHomeTarget(Nest->GetActorLocation(), TrunkBase, (float)FVector::Dist2D(Nest->GetActorLocation(), TrunkBase) - 300.f);
		}
		if (Director->IsNearNest(Movement->GetSurfacePosition()))
		{
			Director->OnAntReachedNest(this);
			return;
		}
	}
	// Walking home yourself with a fragment also counts.
	if (IsPlayerControlled() && IsCarrying() && Movement->GetState() == EAntState::Walking &&
		Director->IsNearNest(Movement->GetSurfacePosition()))
	{
		Director->OnAntReachedNest(this);
	}
}

void AAntPawn::UpdateCutting(float Dt)
{
	ATreeActor* Tree = GetTree();
	if (!Tree)
	{
		bPrevCutHeld = bCutHeld;
		return;
	}
	if (CuttingLeaf == INDEX_NONE)
	{
		const bool bPressed = bCutHeld && !bPrevCutHeld;
		if (bPressed && LeafInReach != INDEX_NONE && !IsCarrying() && Movement->GetState() == EAntState::Walking)
		{
			CuttingLeaf = LeafInReach;
			CutSize = 0.f;
			CutCap = Tree->LeafSizeCap(CuttingLeaf, Cut.LeafUsePerCut);
			Movement->SetState(EAntState::Cutting);
			CutLoop = LeafSound::Loop(this, TEXT("cut_loop"), 0.5f);
			UE_LOG(LogLeafline, Log, TEXT("%s: cutting leaf %d (size cap %.2f)"), *GetName(), CuttingLeaf, CutCap);
		}
	}
	else if (bAutoCut)
	{
		CutSize = FMath::Min(CutCap, CutSize + Cut.CutRate * CutRateMultiplier * Dt);
		if (CutSize >= CutCap - 1e-4f) FinishCut();
	}
	else if (bCutHeld && IsPlayerControlled())
	{
		CutSize = FMath::Min(CutCap, CutSize + Cut.CutRate * CutRateMultiplier * Dt);
	}
	else
	{
		FinishCut();
	}
	bPrevCutHeld = bCutHeld;
}

void AAntPawn::FinishCut()
{
	ATreeActor* Tree = GetTree();
	if (!Tree || CuttingLeaf == INDEX_NONE) return;
	// Where the piece comes out, taken before the bite changes the leaf.
	FVector2f BiteC(0.f, 0.f);
	float BiteR = 0.f;
	Tree->GetLeaves().PlanBite(CuttingLeaf, DiameterForSize(CutSize), BiteC, BiteR);
	const FTreeLeaf LeafBefore = Tree->GetLeaves().Get(CuttingLeaf);
	// Someone else may have bitten this leaf since the cut began: never take more than it still allows. A recruit
	// cuts its line's size or nothing.
	const float CapNow = Tree->LeafSizeCap(CuttingLeaf, Cut.LeafUsePerCut);
	if (bAutoCut && CapNow < CutSize - 0.001f) CutSize = 0.f;
	CutSize = FMath::Min(CutSize, CapNow);
	if (CutSize >= Cut.MinSize && Tree->BiteLeaf(CuttingLeaf, CutSize, DiameterForSize(CutSize), Cut.LeafUsePerCut))
	{
		if (ADayDirector* D = ADayDirector::Get(this)) D->NoteCut(CuttingLeaf);
		CarriedRichness = FMath::Max(LeafBefore.Richness, 1.f);
		SetFragment(CutSize);
		LastCut.Leaf = CuttingLeaf;
		LastCut.Branch = Movement->GetCurrentBranch();
		LastCut.Pos = Movement->GetSurfacePosition();
		LastCut.Normal = Movement->GetSurfaceNormal();
		LastCut.Size = CutSize;
		LastCut.Richness = CarriedRichness;
		// The tear now; the pickup sound plays when the piece lands on the back (UpdateCutVisuals).
		if (!bRecruit) LeafSound::Play(this, TEXT("cut_done"), 0.7f);
		StartFragmentSwing(LeafBefore.Point(BiteC.X, BiteC.Y), LeafBefore.Dir, LeafBefore.Normal);
		UE_LOG(LogLeafline, Log, TEXT("%s: cut a fragment of size %.2f (mass %.1f, rich x%.2f, %.0f cm) from leaf %d"),
			*GetName(), CutSize, CarriedMass, CarriedRichness, DiameterForSize(CutSize), CuttingLeaf);
	}
	else
	{
		UE_LOG(LogLeafline, Log, TEXT("%s: cut cancelled at size %.2f"), *GetName(), CutSize);
	}
	CuttingLeaf = INDEX_NONE;
	CutSize = 0.f;
	bAutoCut = false;
	LeafSound::Stop(CutLoop);
	if (Movement->GetState() == EAntState::Cutting) Movement->SetState(EAntState::Walking);
}

void AAntPawn::StartFragmentSwing(const FVector& WorldCenter, const FVector& LeafDir, const FVector& LeafNormal)
{
	if (!FragmentMesh) return;
	// The fragment mesh stands in its local XZ plane (face along local Y) with its centre about one radius above its
	// origin. Lay it in the leaf's plane, centred on the bite.
	const FQuat Rot = FRotationMatrix::MakeFromXY(LeafDir, LeafNormal).ToQuat();
	const float R = DiameterForSize(CarriedSize) * 0.5f;
	SwingFrom = FTransform(Rot, WorldCenter - Rot.RotateVector(FVector(-2.f, 0.f, R * 0.95f)));
	SwingTime = 0.f;
	FragmentMesh->SetWorldTransform(SwingFrom);
	UE_LOG(LogLeafline, Log, TEXT("%s: piece tears out %.0f cm from the mouth and swings onto the back"), *GetName(),
		FVector::Dist(WorldCenter, CarrySocket ? CarrySocket->GetComponentLocation() : GetActorLocation()));
}

void AAntPawn::DepositAndVanish(const FVector& Entrance)
{
	// The vanish is a visual: it plays on the actor's own tick, in real time, even for a sim-stepped ant.
	if (bSimDriven) SetSimDriven(false);
	LeafSound::Stop(CutLoop);
	LeafSound::Stop(GripLoop);
	if (Movement) Movement->SetComponentTickEnabled(false);
	VanishTime = 0.f;
	VanishFrom = GetActorLocation();
	VanishTo = Entrance;
	bVanishPiece = IsCarrying() && FragmentMesh;
	SwingTime = -1.f;
	if (bVanishPiece) VanishPieceFrom = FragmentMesh->GetComponentTransform();
}

void AAntPawn::UpdateVanish(float Dt)
{
	constexpr float Duration = 0.7f;
	VanishTime += Dt;
	const float T = FMath::Clamp(VanishTime / Duration, 0.f, 1.f);
	// The ant heads into the entrance and sinks down it.
	const float Walk = FMath::SmoothStep(0.f, 1.f, FMath::Min(T / 0.7f, 1.f));
	const float Sink = FMath::SmoothStep(0.5f, 1.f, T);
	SetActorLocation(FMath::Lerp(VanishFrom, VanishTo, (double)Walk) - FVector(0.0, 0.0, 14.0 * Sink));
	if (VisualRoot) VisualRoot->SetRelativeScale3D(FVector(FMath::Lerp(1.f, 0.35f, Sink)));
	// The piece drops into the entrance ahead of the ant and shrinks away.
	if (bVanishPiece && FragmentMesh)
	{
		const float E = FMath::SmoothStep(0.f, 1.f, FMath::Min(T / 0.6f, 1.f));
		const FVector Loc = FMath::Lerp(VanishPieceFrom.GetLocation(), VanishTo, (double)E) + FVector(0.0, 0.0, 10.0 * FMath::Sin(PI * E));
		FragmentMesh->SetWorldLocation(Loc);
		FragmentMesh->SetWorldScale3D(VanishPieceFrom.GetScale3D() * FMath::Lerp(1.f, 0.1f, E));
	}
	if (T >= 1.f)
	{
		ClearFragment();
		Destroy();
	}
}

void AAntPawn::ReattachFragment()
{
	if (!FragmentMesh || !CarrySocket) return;
	FlutterTime = -1.f;
	if (FragmentMesh->GetAttachParent() != CarrySocket)
	{
		FragmentMesh->AttachToComponent(CarrySocket, FAttachmentTransformRules::SnapToTargetNotIncludingScale);
	}
	FragmentMesh->SetRelativeLocationAndRotation(FVector::ZeroVector, FragmentRestRotation);
	FragmentMesh->SetRelativeScale3D(FVector::OneVector);
}

void AAntPawn::UpdateFlutter(float Dt)
{
	if (FlutterTime < 0.f || !FragmentMesh) return;
	constexpr float Duration = 2.4f;
	FlutterTime += Dt;
	if (FlutterTime >= Duration)
	{
		FragmentMesh->SetVisibility(false);
		ReattachFragment();
		return;
	}
	// Carried off on the wind like a leaf: drifting, sinking slowly, tumbling, gone after a couple of seconds.
	FlutterVelocity.Z = FMath::Max(FlutterVelocity.Z - 220.0 * Dt, -90.0);
	FlutterVelocity *= FMath::Pow(0.7, Dt);
	const FVector Wobble = FVector(FMath::Sin(FlutterTime * 7.f), FMath::Cos(FlutterTime * 5.f), 0.f) * 40.f;
	FragmentMesh->SetWorldLocation(FragmentMesh->GetComponentLocation() + (FlutterVelocity + Wobble) * Dt);
	FragmentMesh->AddWorldRotation(FQuat(FlutterSpinAxis, FMath::DegreesToRadians(360.f) * Dt * (1.f - 0.5f * FlutterTime / Duration)));
	const float Fade = FMath::SmoothStep(Duration - 0.7f, Duration, FlutterTime);
	FragmentMesh->SetWorldScale3D(FVector(FMath::Lerp(1.f, 0.05f, Fade)));
}

void AAntPawn::UpdateCutVisuals(float Dt)
{
	// Wind as the ant feels it on this spot (gust strength times the spot's exposure), sampled a few times a second.
	// It drives in-world cues: the carried piece shakes, the body leans and shivers; sheltered spots stay calm.
	const AWindSystem* Wind = AWindSystem::Get(this);
	VisTime += Dt;
	FeltTimer -= Dt;
	if (FeltTimer <= 0.f && Wind && Movement)
	{
		FeltTimer = 0.2f;
		FeltExposure = Wind->GetExposure(Movement->GetSurfacePosition(), Movement->GetSurfaceNormal());
	}
	const float Feel = Wind ? FMath::Clamp(Wind->GetStrength(), 0.f, 1.f) * FeltExposure : 0.f;
	WindFeel = FMath::FInterpTo(WindFeel, Feel, Dt, 3.f);
	const EAntState VisState = Movement ? Movement->GetState() : EAntState::Walking;
	// The origin rides RideHeight above the surface; the mesh is drawn MeshSinkCm lower so its feet touch the bark.
	const float Sink = (Movement && AntMesh) ? Movement->Tuning.MeshSinkCm : 0.f;

	if (Body)
	{
		FRotator Rot = FRotator::ZeroRotator;
		FVector Loc(0.f, 0.f, -Sink);
		FVector Scale = FVector::OneVector;
		// Sawing: while cutting, the body nods quickly and sweeps slowly from side to side, as if working along the arc.
		if (IsCutting())
		{
			SawTime += Dt;
			Rot.Pitch += 4.f * FMath::Sin(SawTime * 2.f * PI * 4.5f);
			Rot.Yaw += 9.f * FMath::Sin(SawTime * 2.f * PI * 0.9f);
			Loc.X += 0.6f * FMath::Sin(SawTime * 2.f * PI * 4.5f);
		}
		else
		{
			SawTime = 0.f;
		}
		// Walking: the body wags and rocks with the stride (one cycle per GaitPhase turn, as the tripods alternate) and
		// bobs twice per cycle, so the walk reads from behind, where the legs are mostly hidden by the body.
		if (Movement && GaitAmount > 0.01f && !IsCutting() && VisState != EAntState::Gripping)
		{
			const FAntMoveTuning& T = Movement->Tuning;
			const float S = FMath::Sin(GaitPhase);
			Rot.Yaw += T.GaitWagDeg * GaitAmount * S;
			Rot.Roll += T.GaitRollDeg * GaitAmount * FMath::Sin(GaitPhase + 0.6f);
			Loc.Z += T.GaitBobCm * GaitAmount * FMath::Abs(FMath::Cos(GaitPhase));
		}
		// Gripping: pressed flat to the bark with the legs spread, trembling with the wind.
		if (VisState == EAntState::Gripping)
		{
			Loc.Z = FMath::Min(Loc.Z, -1.2f); // 1.2 cm down in all, as before the sink (most of it is the sink now)
			Scale = FVector(1.06f, 1.14f, 0.78f);
			Rot.Roll += (0.6f + 2.f * WindFeel) * FMath::Sin(VisTime * 2.f * PI * 9.f);
		}
		// Leaning away from the wind where it reaches the ant.
		else if (Wind && WindFeel > 0.02f && (VisState == EAntState::Walking || VisState == EAntState::Cutting || VisState == EAntState::Riding))
		{
			const FVector Local = GetActorTransform().InverseTransformVectorNoScale(Wind->GetDirection());
			Rot.Roll += 9.f * WindFeel * (float)Local.Y + 1.5f * WindFeel * FMath::Sin(VisTime * 2.f * PI * 6.f);
			Rot.Pitch -= 6.f * WindFeel * (float)Local.X;
		}
		Body->SetRelativeLocationAndRotation(Loc, Rot);
		Body->SetRelativeScale3D(Scale);
	}
	// The carried piece is held in the jaws, so its socket goes down with the mesh (not with the sway, as before).
	if (CarrySocket)
	{
		const FVector SocketLoc = MandibleOffset - FVector(0.f, 0.f, Sink);
		if (!CarrySocket->GetRelativeLocation().Equals(SocketLoc, 0.01f)) CarrySocket->SetRelativeLocation(SocketLoc);
	}

	// The carried piece shakes in the wind like a small sail: barely in shelter, hard on an exposed face in a gust.
	if (IsCarrying() && SwingTime < 0.f && FlutterTime < 0.f && VanishTime < 0.f && FragmentMesh)
	{
		const float A = 2.f + 28.f * WindFeel;
		const float F = 2.5f + 4.f * WindFeel;
		const FRotator Shake(A * 0.6f * FMath::Sin(VisTime * 2.f * PI * F), A * 0.35f * FMath::Sin(VisTime * 2.f * PI * F * 0.73f + 1.3f),
			A * FMath::Sin(VisTime * 2.f * PI * F * 1.21f + 0.4f));
		FragmentMesh->SetRelativeRotation(FragmentRestRotation + Shake);
	}

	// The torn piece swings up from the leaf over the ant onto its back.
	if (SwingTime >= 0.f && FragmentMesh && CarrySocket)
	{
		constexpr float Duration = 0.45f;
		SwingTime += Dt;
		const FTransform Rest = FTransform(FragmentRestRotation) * CarrySocket->GetComponentTransform();
		if (SwingTime >= Duration || !IsCarrying())
		{
			SwingTime = -1.f;
			FragmentMesh->SetRelativeLocationAndRotation(FVector::ZeroVector, FragmentRestRotation);
			if (IsCarrying()) LeafSound::Play(this, TEXT("pickup"), 0.45f, 1.1f - 0.2f * CarriedSize);
			return;
		}
		const float E = FMath::SmoothStep(0.f, 1.f, SwingTime / Duration);
		const FVector Up = GetActorUpVector();
		const double Arc = FMath::Max(14.0, 0.3 * FVector::Dist(SwingFrom.GetLocation(), Rest.GetLocation()));
		const FVector Loc = FMath::Lerp(SwingFrom.GetLocation(), Rest.GetLocation(), (double)E) + Up * (Arc * FMath::Sin(PI * E));
		const FQuat Rot = FQuat::Slerp(SwingFrom.GetRotation(), Rest.GetRotation(), E);
		FragmentMesh->SetWorldLocationAndRotation(Loc, Rot);
	}
}

bool AAntPawn::DebugCutNow(float Size01)
{
	ATreeActor* Tree = GetTree();
	if (!Tree || IsCarrying()) return false;
	const int32 Leaf = Tree->FindLeafNear(GetActorTransform().TransformPosition(MandibleOffset), Cut.Reach);
	if (Leaf == INDEX_NONE) return false;
	const float Size = FMath::Min(Size01, Tree->LeafSizeCap(Leaf, Cut.LeafUsePerCut));
	const float Richness = FMath::Max(Tree->GetLeaves().Get(Leaf).Richness, 1.f);
	if (!Tree->BiteLeaf(Leaf, Size, DiameterForSize(Size), Cut.LeafUsePerCut)) return false;
	if (ADayDirector* D = ADayDirector::Get(this)) D->NoteCut(Leaf);
	CarriedRichness = Richness;
	SetFragment(Size);
	LastCut.Leaf = Leaf;
	LastCut.Branch = Movement->GetCurrentBranch();
	LastCut.Pos = Movement->GetSurfacePosition();
	LastCut.Normal = Movement->GetSurfaceNormal();
	LastCut.Size = Size;
	LastCut.Richness = Richness;
	UE_LOG(LogLeafline, Log, TEXT("%s: cut a fragment of size %.2f (mass %.1f) from leaf %d"), *GetName(), Size, CarriedMass, Leaf);
	return true;
}

bool AAntPawn::DebugCutLeaf(int32 Leaf, float Size01)
{
	ATreeActor* Tree = GetTree();
	if (!Tree || IsCarrying() || Leaf < 0 || Leaf >= Tree->GetLeaves().Num()) return false;
	const float Size = FMath::Min(Size01, Tree->LeafSizeCap(Leaf, Cut.LeafUsePerCut));
	const FTreeLeaf& L = Tree->GetLeaves().Get(Leaf);
	const float Richness = FMath::Max(L.Richness, 1.f);
	const int32 Branch = L.Branch;
	if (Size < Cut.MinSize || !Tree->BiteLeaf(Leaf, Size, DiameterForSize(Size), Cut.LeafUsePerCut)) return false;
	if (ADayDirector* D = ADayDirector::Get(this)) D->NoteCut(Leaf);
	CarriedRichness = Richness;
	SetFragment(Size);
	LastCut.Leaf = Leaf;
	LastCut.Branch = Movement->GetCurrentBranch() != INDEX_NONE ? Movement->GetCurrentBranch() : Branch;
	LastCut.Pos = Movement->GetSurfacePosition();
	LastCut.Normal = Movement->GetSurfaceNormal();
	LastCut.Size = Size;
	LastCut.Richness = Richness;
	UE_LOG(LogLeafline, Log, TEXT("%s: test cut of size %.2f (mass %.1f, rich x%.2f) from leaf %d"), *GetName(), Size, CarriedMass, Richness, Leaf);
	return true;
}

void AAntPawn::UpdateRiding(float Dt)
{
	ATrailNetwork* Trails = GetTrails();
	const EAntState State = Movement->GetState();
	if (!Trails || !IsPlayerControlled())
	{
		bTrailInReach = false;
		if (Movement) Movement->SetOnTrail(false);
		return;
	}
	TrailCheckTimer -= Dt;
	if (TrailCheckTimer <= 0.f && State == EAntState::Walking)
	{
		TrailCheckTimer = 0.15f;
		int32 P, I;
		ADayDirector* D = GetDirector();
		bTrailInReach = Trails->FindRideStart(Movement->GetSurfacePosition(), D ? D->Tuning.RideReach : 60.f, Movement->GetBodyForward(), P, I, PathIndex);
		// On another worker's trail (not the one this ant is laying under its feet): walk faster.
		Movement->SetOnTrail(bTrailInReach && Trails->FindRideStart(Movement->GetSurfacePosition(), 22.f, Movement->GetBodyForward(), P, I, PathIndex));
	}
	else if (State != EAntState::Walking)
	{
		Movement->SetOnTrail(false);
	}
	if (bFollowHeld && State == EAntState::Walking && !Movement->HasMoveInput())
	{
		int32 Path, Index;
		ADayDirector* D = GetDirector();
		if (Trails->FindRideStart(Movement->GetSurfacePosition(), D ? D->Tuning.RideReach : 60.f, Movement->GetBodyForward(), Path, Index, PathIndex))
		{
			Movement->StartFollow(Trails->GetPoints(Path), Index, 1, EAntState::Riding);
			UE_LOG(LogLeafline, Log, TEXT("%s: riding trail %d from point %d of %d"), *GetName(), Path, Index, Trails->GetPoints(Path).Num());
		}
	}
	else if (!bFollowHeld && State == EAntState::Riding)
	{
		Movement->StopFollow();
	}
}

bool AAntPawn::IsGripping() const
{
	return Movement && Movement->GetState() == EAntState::Gripping;
}

void AAntPawn::UpdateGrip()
{
	if (!IsPlayerControlled()) return;
	const EAntState State = Movement->GetState();
	if (bGripHeld && (State == EAntState::Walking || State == EAntState::Riding))
	{
		if (State == EAntState::Riding) Movement->StopFollow();
		Movement->SetState(EAntState::Gripping);
	}
	else if (!bGripHeld && State == EAntState::Gripping)
	{
		Movement->SetState(EAntState::Walking);
	}
}

float AAntPawn::GetGripMultiplier() const
{
	const ULeaflineGameInstance* GI = Cast<ULeaflineGameInstance>(GetGameInstance());
	return GI ? FMath::Max(GI->GetGripMultiplier(), 0.01f) : 1.f;
}

void AAntPawn::UpdateWind(float Dt)
{
	// Deterministic blow-off: Force = strength * peak * exposure * (body + fragment area) against the grip.
	const AWindSystem* Wind = AWindSystem::Get(this);
	if (!Wind) return;
	const EAntState State = Movement->GetState();
	const bool bCanBeBlown = State == EAntState::Walking || State == EAntState::Riding || State == EAntState::Returning ||
		State == EAntState::Cutting || State == EAntState::Gripping;
	if (!Wind->IsGustActive() || !bCanBeBlown)
	{
		if (bGustSeen && bCanBeBlown)
		{
			UE_LOG(LogLeafline, Log, TEXT("%s: rode out the gust (worst force/hold %.2f, exposure %.2f, fragment %.1f, gripped %d)"),
				*GetName(), GustMaxRatio, GustMaxExposure, CarriedMass, bGustGripped ? 1 : 0);
		}
		bGustSeen = false;
		GustMaxRatio = 0.f;
		GustMaxExposure = 0.f;
		bGustGripped = false;
		return;
	}
	WindCheckTimer -= Dt;
	if (WindCheckTimer > 0.f) return;
	WindCheckTimer = 0.25f;
	float Exposure = 0.f;
	const float Force = Wind->ComputeForce(Movement->GetSurfacePosition(), Movement->GetSurfaceNormal(),
		IsCarrying() ? DiameterForSize(CarriedSize) : 0.f, &Exposure);
	const float Hold = Wind->GetHold(GetGripMultiplier(), State == EAntState::Gripping);
	bGustSeen = true;
	bGustGripped |= State == EAntState::Gripping;
	if (Hold > 0.f && Force / Hold > GustMaxRatio)
	{
		GustMaxRatio = Force / Hold;
		GustMaxExposure = Exposure;
	}
	if (Force > Hold) BlowOff(Force, Hold, Exposure);
}

void AAntPawn::BlowOff(float Force, float Hold, float Exposure, EBlowOffCause Cause)
{
	if (!bRecruit) LeafSound::Play(this, TEXT("blown_off"), 0.8f);
	LeafSound::Stop(CutLoop);
	if (Cause == EBlowOffCause::Bird)
	{
		UE_LOG(LogLeafline, Log, TEXT("%s: knocked off by the bird (exposure %.2f, fragment %.1f, state %s)"),
			*GetName(), Exposure, CarriedMass, *UEnum::GetValueAsString(Movement->GetState()));
	}
	else
	{
		UE_LOG(LogLeafline, Log, TEXT("%s: blown off (force %.2f > hold %.2f, exposure %.2f, fragment %.1f, state %s)"),
			*GetName(), Force, Hold, Exposure, CarriedMass, *UEnum::GetValueAsString(Movement->GetState()));
	}
	if (IsCutting())
	{
		CuttingLeaf = INDEX_NONE;
		CutSize = 0.f;
		bAutoCut = false;
	}
	const bool bHadPiece = IsCarrying();
	ClearFragment();
	bGustSeen = false;
	const AWindSystem* Wind = AWindSystem::Get(this);
	if (bHadPiece && FragmentMesh)
	{
		// The piece is torn away by the wind and flutters off on its own.
		SwingTime = -1.f;
		FragmentMesh->DetachFromComponent(FDetachmentTransformRules::KeepWorldTransform);
		FragmentMesh->SetVisibility(true);
		FVector WindDir = Wind ? Wind->GetDirection().GetSafeNormal() : FVector::ForwardVector;
		const FVector N = Movement->GetSurfaceNormal();
		const double Into = FVector::DotProduct(WindDir, N);
		if (Into < 0.0) WindDir -= N * Into; // off the bark, not into it
		FlutterVelocity = WindDir * 420.0 + N * 200.0 + FVector(0.0, 0.0, 160.0);
		FlutterSpinAxis = FVector(FMath::FRandRange(-1.f, 1.f), FMath::FRandRange(-1.f, 1.f), FMath::FRandRange(-1.f, 1.f)).GetSafeNormal();
		if (FlutterSpinAxis.IsNearlyZero()) FlutterSpinAxis = FVector::UpVector;
		FlutterTime = 0.f;
	}
	if (ADayDirector* D = GetDirector())
	{
		if (ANestActor* Nest = D->GetNest())
		{
			const FVector TrunkBase = GetTree() ? GetTree()->GetSkeleton().TrunkBase : FVector::ZeroVector;
			Movement->SetHomeTarget(Nest->GetActorLocation(), TrunkBase, (float)FVector::Dist2D(Nest->GetActorLocation(), TrunkBase) - 300.f);
		}
	}
	Movement->StartFall(Wind ? Wind->GetDirection() : FVector::ForwardVector);
	if (bRecruit)
	{
		if (ALineSystem* Lines = LineOwner.Get()) Lines->OnRecruitBlownOff(this, bHadPiece);
	}
	else if (ADayDirector* D = GetDirector())
	{
		D->OnBlownOff(this);
	}
}

void AAntPawn::DropCarried()
{
	if (!IsCarrying()) return;
	UE_LOG(LogLeafline, Log, TEXT("%s: drops its piece (%.1f) on the bark"), *GetName(), CarriedMass);
	SwingTime = -1.f;
	ReattachFragment();
	ClearFragment();
	LastCut = FAntCutRecord(); // dropping makes no line; the next cut is the one a send-home builds from
}

void AAntPawn::UpdateSounds()
{
	const bool bControlled = IsPlayerControlled();
	const EAntState State = Movement->GetState();
	// Grip creak while holding on.
	if (bControlled && State == EAntState::Gripping)
	{
		if (!GripLoop) GripLoop = LeafSound::Loop(this, TEXT("grip"), 0.35f);
	}
	else if (GripLoop)
	{
		LeafSound::Stop(GripLoop);
	}
	if (!bControlled) return;
	// Tiny footsteps from distance walked.
	const FVector P = Movement->GetSurfacePosition();
	if (State == EAntState::Walking || State == EAntState::Riding || State == EAntState::WalkingHome)
	{
		StepDistance += (float)FVector::Dist(P, LastStepPos);
		if (StepDistance > 18.f)
		{
			StepDistance = 0.f;
			static const TCHAR* Steps[] = { TEXT("step_01"), TEXT("step_02"), TEXT("step_03"), TEXT("step_04"), TEXT("step_05"), TEXT("step_06") };
			LeafSound::Play(this, Steps[FMath::RandRange(0, 5)], 0.18f, FMath::FRandRange(0.9f, 1.1f));
		}
	}
	LastStepPos = P;
	const bool bLocked = Movement->IsSprintLocked();
	if (bLocked && !bWasSprintLocked) LeafSound::Play(this, TEXT("stamina_low"), 0.45f);
	bWasSprintLocked = bLocked;
}

void AAntPawn::UpdateRecording()
{
	ATrailNetwork* Trails = GetTrails();
	if (PathIndex == INDEX_NONE || !Trails) return;
	const EAntState State = Movement->GetState();
	if (State == EAntState::Returning || State == EAntState::Falling || State == EAntState::WalkingHome) return;
	const ADayDirector* D = GetDirector();
	const float Spacing = D ? D->Tuning.PathSpacing : 10.f;
	const FVector P = Movement->GetSurfacePosition();
	if (FVector::DistSquared(P, LastRecordPos) >= Spacing * Spacing)
	{
		Trails->AddPoint(PathIndex, P, Movement->GetSurfaceNormal());
		LastRecordPos = P;
	}
}

void AAntPawn::StartReturn()
{
	ATrailNetwork* Trails = GetTrails();
	if (!Trails || PathIndex == INDEX_NONE) return;
	Trails->AddPoint(PathIndex, Movement->GetSurfacePosition(), Movement->GetSurfaceNormal());
	// Not a strict replay of this worker's walk: start from the nearby scent line point nearest the nest (any path)
	// and skip the loops, so an ant sent home halfway down the tree goes down, not back up first.
	TArray<FTrailPoint> Route;
	const ATreeActor* Tree = GetTree();
	// The follower walks the straight line and projects onto the nearest bark: a jump is only taken where it stays on it.
	auto CanCross = [Tree](const FVector& A, const FVector& B) { return Tree && Tree->StaysOnBark(A, B); };
	Trails->BuildReturnRoute(Movement->GetSurfacePosition(), Movement->GetSurfaceNormal(), PathIndex, 100.f, CanCross, Route);
	const TArray<FTrailPoint>& Own = Trails->GetPoints(PathIndex);
	auto Length = [](const TArray<FTrailPoint>& Pts)
	{
		double L = 0.0;
		for (int32 k = 1; k < Pts.Num(); ++k) L += FVector::Dist(Pts[k - 1].Pos, Pts[k].Pos);
		return L;
	};
	const int32 OwnPoints = Own.Num();
	const double OwnLength = Length(Own);
	if (Route.Num() < 2) Route = Own;
	Movement->StartFollow(Route, Route.Num() - 1, -1, EAntState::Returning);
	UE_LOG(LogLeafline, Log, TEXT("%s: returning along %d route points, %.0f cm (its own path: %d points, %.0f cm)"),
		*GetName(), Route.Num(), Length(Route), OwnPoints, OwnLength);
}

void AAntPawn::SetFragment(float Size01)
{
	ReattachFragment();
	CarriedSize = FMath::Clamp(Size01, 0.f, 1.f);
	CarriedMass = MassForSize(CarriedSize);
	Movement->CarriedMass = CarriedMass;
	BuildFragmentMesh(DiameterForSize(CarriedSize));
	FragmentMesh->SetVisibility(true);
}

void AAntPawn::ClearFragment()
{
	CarriedSize = 0.f;
	CarriedMass = 0.f;
	CarriedRichness = 1.f;
	if (Movement) Movement->CarriedMass = 0.f;
	FragmentMesh->SetVisibility(false);
}

void AAntPawn::BuildFragmentMesh(float Diameter)
{
	// A piece of leaf, upright in the ant's XZ plane, held by its lower edge like a sail. Round where it was bitten out,
	// with one straight, slightly serrated side where the leaf's own margin ran, and a gentle cup so it is not a flat
	// plate. Drawn with the leaf material, its UVs placed as if it came from near the margin of a 2 m leaf, so the side
	// veins (but not the midrib) show.
	constexpr int32 Segs = 28;
	const float R = Diameter * 0.5f;
	const FVector Center(-2.f, 0.f, R * 0.95f);
	const float Phase = FMath::FRandRange(0.f, 2.f * PI);
	const float Random = FMath::FRand();
	const float Height = FMath::Clamp((float)(GetActorLocation().Z / 30000.0), 0.f, 1.f);
	const float MarginZ = R * 0.62f;
	TArray<FVector> V, N;
	TArray<FVector2D> UV;
	TArray<FLinearColor> Col;
	TArray<FProcMeshTangent> Tan;
	TArray<int32> Tri;
	auto AddVert = [&](float X, float Z)
	{
		const float Cup = 0.14f * (X * X + Z * Z) / FMath::Max(R, 1.f);
		V.Add(Center + FVector(X, Cup, Z));
		N.Add(FVector::RightVector);
		UV.Add(FVector2D(0.45f + X / 200.f, 0.78f + Z / 90.f));
		Col.Add(FLinearColor(1.f, Random, Height, 0.f));
		Tan.Add(FProcMeshTangent(FVector::ForwardVector, false));
	};
	AddVert(0.f, 0.f);
	for (int32 i = 0; i < Segs; ++i)
	{
		const float A = 2.f * PI * i / Segs;
		const float Rr = R * (1.f + 0.06f * FMath::Sin(3.f * A + Phase) + 0.03f * FMath::Sin(7.f * A));
		float X = FMath::Cos(A) * Rr, Z = FMath::Sin(A) * Rr;
		if (Z > MarginZ) Z = MarginZ + 0.025f * R * FMath::Abs(FMath::Sin(X / FMath::Max(R, 1.f) * 9.f)); // the leaf margin
		AddVert(X, Z);
	}
	for (int32 i = 0; i < Segs; ++i)
	{
		const int32 A = 1 + i, B = 1 + (i + 1) % Segs;
		// UE front faces: (b - a) x (c - a) points away from the viewer, who looks down the normal. The leaf material is
		// two-sided, so one face serves both sides.
		const FVector Cross = FVector::CrossProduct(V[A] - V[0], V[B] - V[0]);
		if (FVector::DotProduct(Cross, FVector::RightVector) > 0.0) Tri.Append({ 0, B, A });
		else Tri.Append({ 0, A, B });
	}
	FragmentMesh->CreateMeshSection_LinearColor(0, V, Tri, N, UV, {}, {}, {}, Col, Tan, false, false);
	FragmentMesh->SetRelativeLocationAndRotation(FVector::ZeroVector, FragmentRestRotation); // yawed so the camera behind sees its face, not its edge; leans back slightly over the body
	const ATreeActor* Tree = GetTree();
	if (Tree && Tree->LeafMaterial)
	{
		FragmentMesh->SetMaterial(0, Tree->LeafMaterial);
	}
	else if (BasicMaterial)
	{
		if (!FragmentMID) FragmentMID = UMaterialInstanceDynamic::Create(BasicMaterial, this);
		FragmentMID->SetVectorParameterValue(TEXT("Color"), FragmentColor);
		FragmentMesh->SetMaterial(0, FragmentMID);
	}
}
